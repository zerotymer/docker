-- 최초 DB 생성 직후 1회 실행 (SYSDBA로 실행됨)
-- 파일명 앞 숫자로 실행 순서 지정
-- PDB 이름: Free=FREEPDB1, EE=ORCLPDB1(기본값) → 환경에 맞게 수정

WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  v_pdb VARCHAR2(128);
BEGIN
  SELECT name INTO v_pdb FROM v$pdbs WHERE name <> 'PDB$SEED' AND ROWNUM = 1;
  EXECUTE IMMEDIATE 'ALTER SESSION SET CONTAINER = ' || v_pdb;
  EXECUTE IMMEDIATE 'CREATE USER app IDENTIFIED BY "App_Pass_123" QUOTA UNLIMITED ON USERS';
  -- 26ai: DB_DEVELOPER_ROLE 제공 / 19c: CONNECT, RESOURCE 로 대체
  BEGIN
    EXECUTE IMMEDIATE 'GRANT DB_DEVELOPER_ROLE TO app';
  EXCEPTION WHEN OTHERS THEN
    EXECUTE IMMEDIATE 'GRANT CONNECT, RESOURCE TO app';
  END;
END;
/
